import base64, io, sys
from fontTools.ttLib import TTFont
from fontTools import subset
LIB="/usr/share/fonts/truetype/liberation/LiberationSans-{}.ttf"
DJ={"Regular":"/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf","Bold":"/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf","Italic":"/usr/share/fonts/truetype/dejavu/DejaVuSans-Oblique.ttf"}
CHARS="".join(chr(c) for c in range(0x20,0x7f))+"₹−–—…’‘“”•·×°"
def build(style):
    f=TTFont(LIB.format(style))
    opts=subset.Options(); opts.name_IDs=["*"]; opts.notdef_outline=True; opts.layout_features=[]; opts.hinting=False
    s=subset.Subsetter(opts); s.populate(unicodes=[ord(c) for c in CHARS if ord(c)!=0x20B9]); s.subset(f)
    d=TTFont(DJ[style]); dg=d.getBestCmap()[0x20B9]
    assert f["head"].unitsPerEm==d["head"].unitsPerEm
    g=d["glyf"][dg]; name="uni20B9"
    f["glyf"].glyphs[name]=g; f.setGlyphOrder(f.getGlyphOrder()+[name])
    f["hmtx"].metrics[name]=d["hmtx"].metrics[dg]
    for t in f["cmap"].tables:
        if t.isUnicode(): t.cmap[0x20B9]=name
    f["maxp"].numGlyphs=len(f.getGlyphOrder())
    b=io.BytesIO(); f.save(b); return base64.b64encode(b.getvalue()).decode()
out=["/* AUTO-GENERATED by scripts/make_assets.py — fonts: Liberation Sans (metric-compatible with Arial, SIL OFL 1.1) subset + ₹ glyph from DejaVu Sans (free licence). Logo: Geeks of Gurukul (from GoG_Salary_Slip.xlsx). */"]
for st,var in [("Regular","SANS_REGULAR"),("Bold","SANS_BOLD"),("Italic","SANS_ITALIC")]:
    out.append(f'export const {var} = "{build(st)}";')
out.append(f'export const LOGO_JPEG = "{base64.b64encode(open(sys.argv[1],"rb").read()).decode()}";')
open(sys.argv[2],"w").write("\n".join(out)+"\n")